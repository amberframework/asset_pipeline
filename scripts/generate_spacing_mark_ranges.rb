#!/usr/bin/ruby
# Regenerates src/asset_pipeline/text_scanning/spacing_mark_ranges.cr from the
# Crystal standard library's Unicode tables (categories Mc and Me).
#
#   /usr/bin/ruby scripts/generate_spacing_mark_ranges.rb \
#     "$(crystal-alpha env CRYSTAL_PATH | tr ':' '\n' | grep -v '^lib$' | head -1)/unicode/data.cr"
#
# The ranges let TextScanning.word_char? tell nonspacing marks (Mn, which
# PCRE2 counts as word characters) apart from the other marks.

data_path = ARGV.fetch(0) { abort "usage: generate_spacing_mark_ranges.rb <crystal src>/unicode/data.cr" }
data = File.read(data_path)
ranges = []
%w[Mc Me].each do |category|
  body = data[/class_getter category_#{category} .*?\n  end/m] or abort "category #{category} not found in #{data_path}"
  body.scan(/put\(data, (\d+), (\d+), (\d+)\)/) { |first, last, stride| ranges << [first.to_i, last.to_i, stride.to_i] }
end
ranges.sort!
unicode_version = data_path.sub(%r{/data\.cr\z}, "/unicode.cr")
version = File.exist?(unicode_version) ? File.read(unicode_version)[/VERSION = "([^"]+)"/, 1] : "unknown"

target = File.expand_path("../src/asset_pipeline/text_scanning/spacing_mark_ranges.cr", __dir__)
File.open(target, "w") do |file|
  file.puts "# GENERATED by scripts/generate_spacing_mark_ranges.rb from the Crystal"
  file.puts "# standard library's Unicode #{version} tables. Do not edit by hand."
  file.puts
  file.puts "module AssetPipeline::TextScanning"
  file.puts "  # Spacing (Mc) and enclosing (Me) mark ranges as {first, last, stride}."
  file.puts "  SPACING_MARK_RANGES = ["
  ranges.each_slice(3) do |row|
    file.puts "    " + row.map { |first, last, stride| format("{0x%04X, 0x%04X, %d},", first, last, stride) }.join(" ")
  end
  file.puts "  ]"
  file.puts "end"
end
puts "wrote #{ranges.size} ranges to #{target}"
